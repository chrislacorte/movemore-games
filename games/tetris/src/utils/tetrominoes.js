export function randomPieceType() {
  return PIECE_TYPES[Math.floor(Math.random() * PIECE_TYPES.length)]
}

export function getCells(type, rotation, row, col) {
  return SHAPES[type][rotation].map(([dr, dc]) => [row + dr, col + dc])
}

export function rotateIndex(rotation, direction) {
  if (direction === 'cw') return (rotation + 1) % 4
  if (direction === 'ccw') return (rotation + 3) % 4
  return rotation
}
